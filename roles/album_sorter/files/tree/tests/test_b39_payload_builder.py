"""B39 (improvement Phase A) - the shared verifier-payload
builder.

try_link (production) and validate_linkage.rebuild_question
(the harness) used to construct the linkage verifier
question in two hand-synced copies; any production payload
edit would silently invalidate every validation arm, whose
scoring would still look fine against its own copy. Both
now call album_sorter.linkage.build_verifier_question.
These tests pin the equivalence (builder output == the
parts try_link actually sends == the harness's rebuilt
question), pin the historical decision keys the default
question hashes to, and pin that a non-default payload
mode joins the key material so text verdicts can never
replay as image verdicts."""
import json
import sqlite3
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import validate_linkage
from album_sorter.config import Config
from album_sorter.gemini_client import StubClient
from album_sorter.journal import decision_key
from album_sorter.linkage import (VERIFIER_SYSTEM,
                                  build_verifier_question,
                                  try_link)
from album_sorter.manifest import Manifest

# Pinned 2026-10-23 from the PRE-B39 construction (the two
# copies agreed; generated by validate_linkage.
# rebuild_question on this exact fixture). If either hex
# changes, the default question changed - that is a
# key-breaking event, not a test bug.
PINNED_KEY2 = ("06b3d105be1ad25077cd0a5692d28d0df2550203"
               "c87fb4a31754ef4643cdc28b")
PINNED_KEY1 = ("a69e1fa2298ab0978a0aa783c3805d62edd4342"
               "96091fa30a31c4ed8d05e6b04")

LOOSE_MD5 = "f" * 32
ANALYSIS = ('{"description": "a dinosaur skeleton in a hall", '
            '"objects": ["skeleton"]}')


def _setup(tmp: Path):
    man = Manifest(tmp / "m.sqlite3")
    eid = man.create_episode("museum visit",
                             ["a" * 32, "b" * 32, "c" * 32])
    for i, t in enumerate(("2026-07-29T10:00:00",
                           "2026-07-29T12:00:00")):
        man.upsert_item(md5=f"{i:032x}", done_name=f"in{i}.jpg",
                        capture_time=t, capture_time_raw=t,
                        episode_id=eid, status="grouped",
                        category="PHOTO")
    man.recompute_episode_span(eid)
    man.upsert_item(md5=LOOSE_MD5, done_name="loose.jpg",
                    capture_time="2026-07-29T11:00:00",
                    capture_time_raw="2026-07-29T11:00:00",
                    status="analyzed", category="PHOTO",
                    analysis_json=ANALYSIS)
    return man, eid


def _built(cfg, man, eid, mode="images"):
    item = man.get_by_md5(LOOSE_MD5)
    ep = man.get_episode(eid)
    exemplars = json.loads(ep["exemplars"] or "[]")[:4]
    out = build_verifier_question(cfg, item, ep, exemplars,
                                  mode=mode)
    return item, exemplars, out


def _keys(cfg, item, exemplars, prompt_text, key_text, extra):
    key2 = decision_key(
        "linkage", cfg.phase1_model_flash, VERIFIER_SYSTEM,
        {"text": key_text, "item_md5": item["md5"],
         "exemplars": exemplars}, extra=extra)
    key1 = decision_key(
        "linkage", cfg.phase1_model_flash, VERIFIER_SYSTEM,
        {"text": prompt_text, "item_md5": item["md5"],
         "exemplars": exemplars}, extra=extra)
    return key2, key1


def test_builder_output_matches_try_link_call():
    with tempfile.TemporaryDirectory() as td:
        man, eid = _setup(Path(td))
        cfg = Config()
        item, exemplars, (prompt_text, key_text, parts, extra) = \
            _built(cfg, man, eid)
        key2, _key1 = _keys(cfg, item, exemplars, prompt_text,
                            key_text, extra)
        client = StubClient(
            lambda m, s, p: {"verdict": "yes", "confidence": 0.95})
        assert try_link(cfg, man, client, item) is True
        assert len(client.calls) == 1
        # production sent exactly the builder's parts
        assert client.calls[0]["parts"] == parts
        assert client.calls[0]["system"] == VERIFIER_SYSTEM
        # and journaled the verdict under the builder's key
        row = man.get_decision(key2)
        assert row is not None
        assert json.loads(row["result_json"])["verdict"] == "yes"


def test_builder_output_matches_harness_rebuild():
    with tempfile.TemporaryDirectory() as td:
        man, eid = _setup(Path(td))
        cfg = Config()
        item, exemplars, (prompt_text, key_text, parts, extra) = \
            _built(cfg, man, eid)
        key2, key1 = _keys(cfg, item, exemplars, prompt_text,
                           key_text, extra)
        raw = sqlite3.connect(
            f"file:{Path(td) / 'm.sqlite3'}?mode=ro", uri=True)
        raw.row_factory = sqlite3.Row
        try:
            built = validate_linkage.rebuild_question(
                cfg, man, raw,
                {"md5": LOOSE_MD5, "episode_id": eid}, 4)
        finally:
            raw.close()
        assert built is not None
        h_parts, h_key2, h_key1 = built
        assert h_parts == parts
        assert h_key2 == key2
        assert h_key1 == key1


def test_images_mode_reproduces_pinned_historical_key():
    with tempfile.TemporaryDirectory() as td:
        man, eid = _setup(Path(td))
        cfg = Config()
        item, exemplars, (prompt_text, key_text, parts, extra) = \
            _built(cfg, man, eid)
        key2, key1 = _keys(cfg, item, exemplars, prompt_text,
                           key_text, extra)
        assert key2 == PINNED_KEY2
        assert key1 == PINNED_KEY1
        # at mode="images" the extra is exactly the historical
        # one - no payload_mode, no new keys
        assert "payload_mode" not in extra


def test_text_mode_parts_and_key():
    with tempfile.TemporaryDirectory() as td:
        man, eid = _setup(Path(td))
        cfg = Config()
        item, exemplars, (p_i, k_i, _parts_i, extra_i) = \
            _built(cfg, man, eid)
        _i2, _e2, (p_t, k_t, parts_t, extra_t) = \
            _built(cfg, man, eid, mode="text")
        # text mode asks the same question in words: identical
        # prompt/key texts, and no image parts at all
        assert p_t == p_i and k_t == k_i
        assert parts_t == [{"text": p_t}]
        assert all("image_md5" not in part for part in parts_t)
        # the mode joins the key material, so a text verdict
        # can never replay as an image verdict (or back)
        assert extra_t["payload_mode"] == "text"
        key_i, _ = _keys(cfg, item, exemplars, p_i, k_i, extra_i)
        key_t, _ = _keys(cfg, item, exemplars, p_t, k_t, extra_t)
        assert key_t != key_i


def test_sheet_mode_not_built_yet():
    with tempfile.TemporaryDirectory() as td:
        man, eid = _setup(Path(td))
        cfg = Config()
        item = man.get_by_md5(LOOSE_MD5)
        ep = man.get_episode(eid)
        exemplars = json.loads(ep["exemplars"] or "[]")[:4]
        try:
            build_verifier_question(cfg, item, ep, exemplars,
                                    mode="sheet")
        except NotImplementedError:
            pass
        else:
            raise AssertionError(
                "sheet mode must stay unbuilt until Phase C "
                "(B38)")
